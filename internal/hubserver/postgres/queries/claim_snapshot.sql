LEFT JOIN LATERAL (SELECT * FROM issues i WHERE i.organization_id=sqlc.arg(organization_id) AND i.project_id=sqlc.arg(project_id) AND i.id>=q.id AND i.id<=q.id ORDER BY i.id LIMIT 1 OFFSET 0) i ON true
