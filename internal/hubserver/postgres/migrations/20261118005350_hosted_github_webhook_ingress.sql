CREATE FUNCTION public.hosted_github_webhook_authorized(delivery text, project text, repo text, event text, digest text, lock_rows boolean) RETURNS boolean
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
DECLARE
    org text := current_setting('detent.organization_id',true);
BEGIN
    IF lock_rows THEN
        PERFORM FROM platform.organizations WHERE id=org FOR SHARE;
        IF NOT FOUND THEN RETURN false; END IF;
        PERFORM FROM public.hosted_tenant WHERE organization_id=org FOR SHARE;
        IF NOT FOUND THEN RETURN false; END IF;
        PERFORM FROM public.projects WHERE organization_id=org AND id=project FOR SHARE;
        IF NOT FOUND THEN RETURN false; END IF;
        PERFORM FROM public.project_settings WHERE organization_id=org AND project_id=project FOR SHARE;
        IF NOT FOUND THEN RETURN false; END IF;
    END IF;
    RETURN EXISTS (
        SELECT FROM platform.github_webhook_ingress i
        JOIN platform.organizations o ON o.id=org AND o.state='ready'
        JOIN public.hosted_tenant h ON h.organization_id=o.id AND h.allocation_generation=o.generation
        JOIN public.projects p ON p.organization_id=o.id AND p.id=project AND p.profile='native' AND p.deleted_at IS NULL
        JOIN public.project_settings s ON s.organization_id=p.organization_id AND s.project_id=p.id
        WHERE i.delivery_id=delivery AND i.repository=repo AND i.repository<>'' AND i.event_type=event AND i.payload_digest=digest AND i.state='routing'
        AND (o.github_binding_xid IS NULL OR pg_visible_in_snapshot(o.github_binding_xid,i.accepted_snapshot))
        AND (p.github_binding_xid IS NULL OR pg_visible_in_snapshot(p.github_binding_xid,i.accepted_snapshot))
        AND ((lower(s.repository)=i.repository AND (s.github_repository_xid IS NULL OR pg_visible_in_snapshot(s.github_repository_xid,i.accepted_snapshot)))
          OR (lower(s.checkout_repository)=i.repository AND (s.github_checkout_xid IS NULL OR pg_visible_in_snapshot(s.github_checkout_xid,i.accepted_snapshot))))
    );
END
$$;
