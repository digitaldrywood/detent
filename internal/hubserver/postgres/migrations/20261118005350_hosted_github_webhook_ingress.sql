-- +goose StatementBegin
CREATE FUNCTION public.mark_github_repository_binding() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $$
BEGIN
    IF TG_OP = 'INSERT' OR (NEW.organization_id,NEW.project_id) IS DISTINCT FROM (OLD.organization_id,OLD.project_id) THEN
        NEW.github_repository_xid := pg_current_xact_id();
        NEW.github_checkout_xid := NEW.github_repository_xid;
    ELSE
        NEW.github_repository_xid := CASE WHEN lower(NEW.repository) IS DISTINCT FROM lower(OLD.repository)
            THEN pg_current_xact_id() ELSE OLD.github_repository_xid END;
        NEW.github_checkout_xid := CASE WHEN lower(NEW.checkout_repository) IS DISTINCT FROM lower(OLD.checkout_repository)
            THEN pg_current_xact_id() ELSE OLD.github_checkout_xid END;
    END IF;
    RETURN NEW;
END
$$;
-- +goose StatementEnd
CREATE TRIGGER github_repository_binding BEFORE INSERT OR UPDATE OF organization_id,project_id,repository,checkout_repository,github_repository_xid,github_checkout_xid ON public.project_settings
FOR EACH ROW EXECUTE FUNCTION public.mark_github_repository_binding();

CREATE TABLE platform.github_webhook_ingress (
    delivery_id text PRIMARY KEY,
    event_type text NOT NULL,
    repository text NOT NULL,
    payload_digest text NOT NULL,
    payload_object_key text NOT NULL,
    accepted_snapshot pg_snapshot NOT NULL DEFAULT pg_current_snapshot(),
    last_received_at timestamptz NOT NULL,
    state text NOT NULL CHECK (state IN ('staging','routing','cleanup','completed')),
    after_organization text NOT NULL DEFAULT '',
    after_project text NOT NULL DEFAULT '',
    pass_failed boolean NOT NULL DEFAULT false,
    attempts bigint NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL,
    dispatch_order bigint GENERATED BY DEFAULT AS IDENTITY
);
CREATE INDEX github_webhook_ingress_due ON platform.github_webhook_ingress(next_attempt_at,dispatch_order) WHERE state IN ('staging','routing','cleanup');
CREATE INDEX github_webhook_ingress_received ON platform.github_webhook_ingress(last_received_at DESC) WHERE state<>'staging';
GRANT SELECT, INSERT, UPDATE, DELETE ON platform.github_webhook_ingress TO detent_platform_v2;
GRANT USAGE ON SEQUENCE platform.github_webhook_ingress_dispatch_order_seq TO detent_platform_v2;

