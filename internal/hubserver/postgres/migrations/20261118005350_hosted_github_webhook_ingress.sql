CREATE FUNCTION platform.mark_github_organization_binding() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $$
BEGIN
    IF TG_OP = 'INSERT' OR (NEW.id,NEW.provider_id,NEW.state,NEW.generation) IS DISTINCT FROM (OLD.id,OLD.provider_id,OLD.state,OLD.generation) THEN
        NEW.github_binding_xid := pg_current_xact_id();
    ELSE
        NEW.github_binding_xid := OLD.github_binding_xid;
    END IF;
    RETURN NEW;
END
$$;
